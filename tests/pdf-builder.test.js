import { assemblePdf } from '../core/pdf-builder.js';

console.log('Testing PDF Builder Standards Compliance...');

// Minimal 1x1 white JPEG byte sequence
const sampleJpeg = new Uint8Array([
  0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x01, 0x00, 0x48,
  0x00, 0x48, 0x00, 0x00, 0xFF, 0xDB, 0x00, 0x43, 0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08,
  0x07, 0x07, 0x07, 0x09, 0x09, 0x08, 0x0A, 0x0C, 0x14, 0x0D, 0x0C, 0x0B, 0x0B, 0x0C, 0x19, 0x12,
  0x13, 0x0F, 0x14, 0x1D, 0x1A, 0x1F, 0x1E, 0x1D, 0x1A, 0x1C, 0x1C, 0x20, 0x24, 0x2E, 0x27, 0x20,
  0x22, 0x2C, 0x23, 0x1C, 0x1C, 0x28, 0x37, 0x29, 0x2C, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1F, 0x27,
  0x39, 0x3D, 0x38, 0x32, 0x3C, 0x2E, 0x33, 0x34, 0x32, 0xFF, 0xC0, 0x00, 0x0B, 0x08, 0x00, 0x01,
  0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xFF, 0xC4, 0x00, 0x1F, 0x00, 0x00, 0x01, 0x05, 0x01, 0x01,
  0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
  0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0xFF, 0xDA, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3F,
  0x00, 0x7F, 0x00, 0xFF, 0xD9
]);

const pdfBytes = assemblePdf(
  [{ bytes: sampleJpeg, width: 400, height: 500 }],
  { A4_WIDTH: 595.28, A4_HEIGHT: 841.89, pageSize: 'A4', margin: 20 }
);

const pdfText = new TextDecoder().decode(pdfBytes);

let failed = 0;
function assert(cond, msg) {
  if (!cond) {
    console.error(`❌ Assertion failed: ${msg}`);
    failed++;
  } else {
    console.log(`  ✓ ${msg}`);
  }
}

assert(pdfText.startsWith('%PDF-1.4'), 'Header starts with %PDF-1.4');
assert(pdfText.includes('/Type /Page'), 'Contains valid Page dictionary');
assert(pdfText.includes('/Contents 4 0 R'), 'Page references separate ContentStream object (4 0 R)');
assert(pdfText.includes('/Type /XObject'), 'Contains Image XObject');
assert(pdfText.includes('/Filter /DCTDecode'), 'XObject uses /DCTDecode for embedded JPEG');
assert(pdfText.includes('%%EOF'), 'Ends with valid PDF trailer and %%EOF');
assert(pdfBytes.length > 500, `Generated PDF has valid size (${pdfBytes.length} bytes)`);

if (failed > 0) {
  process.exit(1);
} else {
  console.log('✅ PDF Builder Tests Passed Successfully!');
}
